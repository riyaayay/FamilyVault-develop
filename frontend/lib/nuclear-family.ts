// Mock-only helper: derives a display status from the due date so fallback
// data never shows a stale "upcoming" for a past date. The live backend
// computes status server-side; explicitly finished items stay "done".
function statusFor(dueDate: string, done = false): "upcoming" | "overdue" | "done" {
  if (done) return "done";
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return new Date(dueDate + "T00:00:00") < today ? "overdue" : "upcoming";
}

