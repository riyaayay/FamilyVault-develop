// health-record ids are generated by the database at seed time, so those
// keep local slugs ("barnaby", "rec-1", ...).

// Mirrors `family_memberships.role` (schema.sql)
export type MembershipRole = "ADMIN" | "MEMBER" | "CHILD" | "VIEWER";

// Mirrors `family_memberships.relation_to_head` (schema.sql)
export type RelationToHead =
  | "HEAD"
  | "SPOUSE"
  | "CHILD"
  | "PARENT"
  | "SIBLING"
  | "EXTENDED";

// Mirrors `users` joined with `family_memberships` for one nuclear household.
// initials/accent are UI-only — computed client-side, not stored in the DB.
export type FamilyMember = {
  id: string; // users.id (UUID)
  fullName: string; // users.full_name
  avatarUrl?: string; // users.avatar_url
  role: MembershipRole; // family_memberships.role
  relationToHead: RelationToHead; // family_memberships.relation_to_head
  initials: string; // derived client-side from fullName
  accent: "chart-1" | "chart-2" | "chart-3" | "chart-4" | "chart-5"; // derived client-side
};

// Pets are NOT FamilyMembers in the real schema — separate table, no
// shared identity with `users`, no `role`/`relation_to_head`.
export type Pet = {
  id: string; // pets.id
  nuclearFamilyId: string;
  name: string;
  petType: "DOG" | "CAT" | "BIRD" | "OTHER"; // pets.pet_type
  breed?: string;
  initials: string; // derived client-side
  accent: "chart-1" | "chart-2" | "chart-3" | "chart-4" | "chart-5"; // derived client-side
};

export type Visibility = "JOINT_CLAN" | "NUCLEAR_HOUSEHOLD" | "PRIVATE_STRICT";

// Mirrors `documents` (only table with visibility_tier)
export type PersonalRecord = {
  id: string;
  title: string;
  category: "document" | "property";
  ownerId: string; // documents.uploader_id -> FamilyMember id
  visibility: Visibility; // documents.visibility_tier
  updatedAt: string; // ISO date
};

// Mirrors `health_records` — NO visibility_tier column.
// Access = owner OR nuclear-family member OR (is_emergency_visible AND same joint family).
export type HealthReminder = {
  id: string;
  personId: string; // health_records.user_id -> FamilyMember id
  label: string;
  dueDate: string; // ISO date
  status: "upcoming" | "overdue" | "done";
};

// Mirrors an entry inside `pets.vaccination_schedule` JSONB.
// Access = is_member_of_nuclear_family only — no visibility concept.
